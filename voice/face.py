"""面部表情翻译 —— 把「情绪」翻成「一组脸部参数」。

和 mouth.py 的分工（两张脸，互不打架）：
    mouth.py   管嘴   —— 跟着 TTS 的每个字变（归音素）
    face.py    管脸   —— 跟着 LLM 标出的情绪变（归情绪）

两边写的参数完全不重叠：
    嘴   → ParamMouthOpenY / ParamMouthForm           （mouth 独占）
    脸   → ParamEyeLSmile/RSmile · ParamBrowLY/RY · ParamAngleZ · ParamTere

⚠️ 刻意不碰的参数（碰了会出问题）：
    ParamEyeLOpen / ParamEyeROpen  → 归「自动眨眼」，我们一写它就不眨了
    ParamAngleX / ParamAngleY      → 留给以后（比如视线跟随观众）

参数范围都跟 Haru 模型核过（2026-10-12 实测）：
    笑眼   0 ~ 1        眉高  -1 ~ 1
    歪头 -30 ~ 30       脸红   0 ~ 1
"""
from __future__ import annotations

# 情绪 → (笑眼, 眉高, 歪头, 脸红)
#
#   笑眼 0~1    ：0 = 平时，1 = 弯成月牙
#   眉高 -1~1   ：+1 = 眉上挑（惊讶/兴奋），-1 = 眉下压（认真/无奈）
#   歪头 -30~30 ：轻微歪头，幅度别超 10，不然像落枕
#   脸红 0~1    ：Haru 的 ParamTere（日语「照れ」），害羞专用
#
# 情绪名要和 cerebrum/brain.py 的 EMOTIONS 对得上（对不上按"中性"处理）。
# 「热情」是行为脑（卖货话术）专用的固定情绪，不来自 LLM。
#
# ⚠️ 这些值是起点不是答案 —— 看着别扭就改数字，重开程序即生效。
情绪到表情 = {
    "开心": (1.00,  0.60,  6.0, 0.00),
    "兴奋": (1.00,  0.90,  9.0, 0.00),
    "惊讶": (0.00,  1.00, -5.0, 0.00),
    "认真": (0.00, -0.40, -3.0, 0.00),
    "害羞": (0.55, -0.20,  6.0, 0.85),
    "无奈": (0.00, -0.50, -7.0, 0.00),
    "温柔": (0.65,  0.20,  4.0, 0.00),
    "热情": (0.85,  0.50,  5.0, 0.00),
    "中性": (0.00,  0.00,  0.0, 0.00),
}

_中性 = 情绪到表情["中性"]


def 情绪到参数(情绪: str) -> dict:
    """情绪字符串 → {参数名: 目标值}。

    渲染主线程每帧调一次；认不出的情绪（含空串）按「中性」处理。
    """
    笑眼, 眉高, 歪头, 脸红 = 情绪到表情.get((情绪 or "").strip(), _中性)
    return {
        "ParamEyeLSmile": 笑眼,
        "ParamEyeRSmile": 笑眼,
        "ParamBrowLY":    眉高,
        "ParamBrowRY":    眉高,
        "ParamAngleZ":    歪头,
        "ParamTere":      脸红,
    }
