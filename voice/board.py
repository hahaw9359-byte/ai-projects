"""黑板 —— 子线程和主线程交换东西的地方。

这是「子线程」和「主线程」之间唯一的桥：
    TTS 工人（子线程）    每合成完一句，把这一句的表、开始时刻、情绪写进来
    渲染循环（主线程）    每一帧读一次
    换模型（双向便签）    子线程写"要换模型"下指令；主线程执行后写回"当前模型"

为什么不用加锁：
    每个键只有一边写；而且写的是"整个换掉"，不是"改一半"。
"""

黑板 = {
    "嘴型表": [],      # [(嘴型, 起秒, 止秒), ...] —— 当前这一句的
    "开始时刻": 0.0,   # 这一句从哪一刻开始播（time.time()）
    "在说": False,     # 现在有没有在说话
    "情绪": "",        # 这一句的情绪（"开心"/"温柔"…，空 = 中性）
    # ── 换模型（网页 ⇄ 主线程 的双向便签）─────────────
    "要换模型": None,  # ← 子线程（网页）写：新模型入口路径；主线程取走后置回 None
    "当前模型": "",    # → 主线程写：现在用的是哪个；网页查它
}


def 播一句(嘴型表: list, 开始时刻: float, 情绪: str = "") -> None:
    """TTS 工人调：把新的一句挂上黑板（整块替换）。

    情绪跟着这一句走 —— 渲染层据此决定脸的样子。
    """
    黑板["嘴型表"] = 嘴型表
    黑板["开始时刻"] = 开始时刻
    黑板["在说"] = True
    黑板["情绪"] = 情绪 or ""


def 说完了() -> None:
    """这一句播完了。

    情绪不主动清空 —— 保持到下一句来替换
    （不然说完话的瞬间会"变回木头脸"，很出戏）。
    """
    黑板["在说"] = False
